const fs = require('fs');
const path = require('path');

const viewsDir = path.join(__dirname, '..', 'src', 'views');

function getFiles(dir) {
  let results = [];
  const list = fs.readdirSync(dir);
  list.forEach(file => {
    file = path.join(dir, file);
    const stat = fs.statSync(file);
    if (stat && stat.isDirectory()) results = results.concat(getFiles(file));
    else if (file.endsWith('.ejs')) results.push(file);
  });
  return results;
}

const files = getFiles(viewsDir);
let code = '/** In-memory EJS templates for Cloudflare Workers & Serverless without filesystem access **/\n';
code += 'module.exports = {\n';

for (const f of files) {
  const rel = path.relative(viewsDir, f).replace(/\\/g, '/');
  const src = fs.readFileSync(f, 'utf8');
  code += `  ${JSON.stringify(rel)}: ${JSON.stringify(src)},\n`;
  code += `  ${JSON.stringify('src/views/' + rel)}: ${JSON.stringify(src)},\n`;
  code += `  ${JSON.stringify(rel.replace(/\.ejs$/, ''))}: ${JSON.stringify(src)},\n`;
}

code += '};\n';

const outPath = path.join(viewsDir, 'rawViews.js');
fs.writeFileSync(outPath, code, 'utf8');
console.log('✅ Generated rawViews.js successfully! Total size:', code.length);

const dummyPrecompiled = path.join(viewsDir, 'precompiledViews.js');
fs.writeFileSync(dummyPrecompiled, '/** Deprecated: digantikan oleh rawViews.js **/\nmodule.exports = {};\n', 'utf8');
console.log('✅ Ensured precompiledViews.js is clean and safe (no with statements).');

// =====================================================
// GENERATE SEED DATA JS (untuk Cloudflare Workers bundle)
// =====================================================
const dataJsonPath = path.join(__dirname, '..', 'data', 'firestore_local.json');
const seedOutPath = path.join(__dirname, '..', 'src', 'data', 'seedData.js');

try {
  const seedDir = path.join(__dirname, '..', 'src', 'data');
  if (!fs.existsSync(seedDir)) fs.mkdirSync(seedDir, { recursive: true });

  let seedData = { admin: {}, client: {}, wajib_lapor: {}, konfigurasi_sistem: {}, history_log: {} };
  if (fs.existsSync(dataJsonPath)) {
    seedData = JSON.parse(fs.readFileSync(dataJsonPath, 'utf8'));
    // Hapus password_plain dari seed data untuk keamanan
    if (seedData.client) {
      for (const id of Object.keys(seedData.client)) {
        if (seedData.client[id].password_plain) {
          delete seedData.client[id].password_plain;
        }
      }
    }
  }

  const seedCode = `/** AUTO-GENERATED by build_views.js - DO NOT EDIT MANUALLY **/
/** Seed data bundled untuk Cloudflare Workers (tanpa akses filesystem) **/
module.exports = ${JSON.stringify(seedData, null, 2)};\n`;

  fs.writeFileSync(seedOutPath, seedCode, 'utf8');
  console.log('✅ Generated src/data/seedData.js successfully! Collections:', Object.keys(seedData).join(', '));
} catch (e) {
  console.warn('⚠️  Gagal generate seedData.js:', e.message);
}
